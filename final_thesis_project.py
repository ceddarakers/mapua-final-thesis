# Section 8.1 - Metric computation and adapter evaluation
from sklearn.metrics import (accuracy_score, f1_score, precision_recall_fscore_support,
                             confusion_matrix, classification_report, cohen_kappa_score)

def compute_metrics(gold, preds):
    p, r, f1, sup = precision_recall_fscore_support(
        gold, preds, labels=[0, 1, 2], zero_division=0)
    m = {"accuracy":    accuracy_score(gold, preds),
         "macro_f1":    f1_score(gold, preds, average="macro",    zero_division=0),
         "weighted_f1": f1_score(gold, preds, average="weighted", zero_division=0)}
    for i, name in enumerate(CLASS_NAMES):
        key = name.lower()
        m[f"f1_{key}"] = f1[i]; m[f"precision_{key}"] = p[i]
        m[f"recall_{key}"] = r[i]; m[f"support_{key}"] = int(sup[i])
    return m

def evaluate_adapter(cfg_name: str, seed: int, split: str = "test"):
    cfg = CONFIGS[cfg_name]
    tag = f"{cfg_name}_seed{seed}"
    ada = f"{PATHS['adapters']}/{tag}"
    assert os.path.isdir(ada), f"No adapter at {ada}. Train it first."
    base  = build_base_model(cfg, for_training=False)   # clean base, same quantization
    model = PeftModel.from_pretrained(base, ada)        # load the TRAINED adapters
    preds, gold, ids, probs = predict_labels(model, ENC[split], batch_size=32, return_probs=True)
    out = pd.DataFrame({"sample_id": ids, "gold": gold, "pred": preds,
                        "p_negative": probs[:, 0], "p_neutral": probs[:, 1],
                        "p_positive": probs[:, 2]})
    out.to_csv(f"{PATHS['predictions']}/{tag}_{split}.csv", index=False)
    m = compute_metrics(gold, preds); m.update({"config": cfg_name, "seed": seed, "split": split})
    with open(f"{PATHS['metrics']}/{tag}_{split}_eval.json", "w") as f:
        json.dump(m, f, indent=2)
    print(f"\n{tag} [{split}]  accuracy {m['accuracy']:.4f} | Macro F1 {m['macro_f1']:.4f} "
          f"| Weighted F1 {m['weighted_f1']:.4f}")
    print(classification_report(gold, preds, target_names=CLASS_NAMES, zero_division=0))
    teardown(model, base)
    return m, out

