# Section 4.2 - Collators: right-padded for training, left-padded for inference
import torch.nn.functional as F
from torch.utils.data import Dataset, DataLoader

PAD_ID = tok_probe.pad_token_id if tok_probe.pad_token_id is not None else tok_probe.eos_token_id

class RecordSet(Dataset):
    def __init__(self, recs): self.recs = recs
    def __len__(self):        return len(self.recs)
    def __getitem__(self, i): return self.recs[i]

def train_collate(batch):
    L = max(len(b["input_ids"]) for b in batch)
    ids  = torch.full((len(batch), L), PAD_ID, dtype=torch.long)
    mask = torch.zeros((len(batch), L), dtype=torch.long)
    for i, b in enumerate(batch):                       # RIGHT pad
        n = len(b["input_ids"])
        ids[i, :n]  = torch.tensor(b["input_ids"], dtype=torch.long)
        mask[i, :n] = 1
    return {"input_ids": ids, "attention_mask": mask,
            "pred_pos":    torch.tensor([b["pred_pos"]    for b in batch], dtype=torch.long),
            "class_label": torch.tensor([b["class_label"] for b in batch], dtype=torch.long)}

def infer_collate(batch):
    L = max(len(b["prompt_ids"]) for b in batch)
    ids  = torch.full((len(batch), L), PAD_ID, dtype=torch.long)
    mask = torch.zeros((len(batch), L), dtype=torch.long)
    for i, b in enumerate(batch):                       # LEFT pad
        n = len(b["prompt_ids"])
        ids[i, L-n:]  = torch.tensor(b["prompt_ids"], dtype=torch.long)
        mask[i, L-n:] = 1
    pos_ids = (mask.cumsum(-1) - 1).clamp(min=0)
    return {"input_ids": ids, "attention_mask": mask, "position_ids": pos_ids,
            "class_label": torch.tensor([b["class_label"] for b in batch], dtype=torch.long),
            "sample_id":   [b["sample_id"] for b in batch]}

