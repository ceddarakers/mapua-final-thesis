# Section 2.1 - PII masking and non-destructive text cleansing
import re

PII_PATTERNS = [
    (re.compile(r"[\w\.\-\+]+@[\w\-]+\.[\w\.\-]+"),            "[EMAIL]"),
    (re.compile(r"(?:\+?63|0)9\d{9}\b"),                        "[PHONE]"),
    (re.compile(r"@[A-Za-z0-9_\.]{3,}"),                        "[USER]"),
    (re.compile(r"\b\d{8,}\b"),                                 "[ORDERID]"),
]
URL_RE   = re.compile(r"https?://\S+|www\.\S+", re.IGNORECASE)
EMOJI_RE = re.compile(
    "[" "\U0001F000-\U0001FAFF" "\U00002600-\U000027BF" "\U0001F1E6-\U0001F1FF"
        "\U00002190-\U000021FF" "\U00002B00-\U00002BFF" "\U0000FE00-\U0000FE0F"
        "\U00002122" "\U000024C2" "]+", flags=re.UNICODE)
# Preserves alphanumerics, Spanish-derived Filipino orthography, sentence punctuation,
# apostrophes, and INTERNAL HYPHENS (nag-download, i-check).
NOISE_RE = re.compile(r"[^A-Za-z0-9\u00f1\u00d1\u00e1\u00e9\u00ed\u00f3\u00fa"
                      r"\u00c1\u00c9\u00cd\u00d3\u00da\s\.\,\!\?\'\-\[\]]")
WS_RE    = re.compile(r"\s+")

def mask_pii(t: str) -> str:
    for pat, rep in PII_PATTERNS:
        t = pat.sub(rep, t)
    return t

def cleanse(t: str) -> str:
    if not isinstance(t, str): return ""
    t = mask_pii(t)          # PII first: URLs and handles may themselves carry identifiers
    t = URL_RE.sub(" ", t)
    t = EMOJI_RE.sub(" ", t)
    t = NOISE_RE.sub(" ", t)
    return WS_RE.sub(" ", t).strip()

