def build_user_msg(text: str) -> str:
    return f"{INSTRUCTION}\n\nReview: {text}\nSentiment:"

def chat_ids(tokenizer, user_msg):
    # Normalises apply_chat_template output across transformers versions.
    # BatchEncoding subclasses UserDict, NOT dict, so isinstance(out, dict) is False.
    out = tokenizer.apply_chat_template(
        [{"role": "user", "content": user_msg}],
        tokenize=True, add_generation_prompt=True)
    if hasattr(out, "input_ids"):
        out = out.input_ids
    elif hasattr(out, "keys") and "input_ids" in out.keys():
        out = out["input_ids"]
    if hasattr(out, "tolist"):
        out = out.tolist()
    while len(out) and isinstance(out[0], (list, tuple)):
        out = out[0]
    return [int(i) for i in out]

def resolve_label_token_ids(tokenizer, label_words):
    ids, report = [], []
    for w in label_words:
        enc = tokenizer.encode(w, add_special_tokens=False)
        ids.append(enc[0])
        report.append({"label": w, "n_tokens": len(enc), "first_id": enc[0],
                       "first_piece": tokenizer.convert_ids_to_tokens(enc[0])})
    assert len(set(ids)) == len(ids), "Label first-tokens collide."
    return torch.tensor(ids, dtype=torch.long), pd.DataFrame(report)

