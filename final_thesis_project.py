def set_all_seeds(seed: int):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)

def teardown(*objs):
    # Explicit VRAM reclamation between runs. PeftModel wrappers, Trainer callbacks,
    # module-level globals and IPython's stored traceback each hold model references
    # that strand VRAM. At 2B scale the residue is harmless; at 9B it causes an OOM
    # on the NEXT run, so every reference path is severed explicitly here.
    for o in objs:
        try:
            if hasattr(o, "callback_handler"):
                o.callback_handler.callbacks = []
            for attr in ("model", "model_wrapped", "base_model", "deepspeed",
                         "optimizer", "lr_scheduler", "accelerator"):
                if hasattr(o, attr):
                    try: setattr(o, attr, None)
                    except Exception: pass
        except Exception: pass
        try: del o
        except Exception: pass

    for _n in ["model", "trainer", "selector", "base", "smoke"]:
        if _n in globals():
            try: del globals()[_n]
            except Exception: pass

    try:
        sys.last_traceback = None; sys.last_value = None; sys.last_type = None
    except Exception: pass

    for _ in range(3):                      # repeated passes break reference cycles
        gc.collect(); torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()

    free, total = torch.cuda.mem_get_info()
    used = (total - free) / 1024**3
    print(f"VRAM after teardown: {used:.2f} GB used / {total/1024**3:.2f} GB")
    if used > 3.0:
        print(f"[!] {used:.1f} GB still held. Restart the session before the next 9B run.")
    return used

