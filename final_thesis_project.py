CONJ = {"at", "and", "tapos", "saka", "pati", "or"}

def _before_words(prefix, n=4):
    """Up to n words before a match, not reaching back past a conjunction ('walang sira AT gumagana')."""
    out = []
    for w in reversed(re.findall(r"[a-z']+|\|", prefix)):
        if w == "|" or w in CONJ or len(out) == n:
            break
        out.append(w)
    return out[::-1]

def _scan(text):
    """Return every expression hit, with negation / hypothetical / packaging handling."""
    hits = []
    norm = normalize(text)
    for si, sent in enumerate(SENT_SPLIT.split(norm)):
        sent_hits = []
        for clause in CLAUSE_SPLIT.split(sent):
            if not clause or not clause.strip():
                continue
            s = clause
            for e in LEX:
                while True:
                    m = e.rx.search(s)
                    if not m:
                        break
                    before = _before_words(s[:m.start()])
                    after  = re.findall(r"[a-z']+", s[m.end():])[:2]
                    s = s[:m.start()] + "|" + " " * (m.end() - m.start() - 1) + s[m.end():]   # mask span (| = barrier)
                    negated = e.negatable and any(w in NEGATORS for w in before)
                    hypo    = e.pol == "neg" and any(w in HYPOTHETICAL for w in before)
                    strength = e.strength
                    if e.id == "S-broken" and (set(before[-2:]) | set(after)) & PACKAGING_WORDS:
                        strength = 1                       # damaged box, not damaged item
                    if e.pol == "pos" and negated:
                        sent_hits.append(Hit("negated-" + e.id, "neg", 2, m.group(0), si))
                    elif e.pol == "neg" and (negated or hypo):
                        continue                           # "walang sira", "baka masira"
                    else:
                        sent_hits.append(Hit(e.id, e.pol, strength, m.group(0), si))
        # resolved serious problem in this sentence?
        rm = RESOLVED.search(sent)
        if rm and not NEG_AFTER.search(sent[rm.end():]):
            sent_hits = [h for h in sent_hits if h.strength != "S"] + \
                        [Hit("resolved-problem", "neu", "R", rm.group(0), si)]
        hits.extend(sent_hits)
    return hits, norm

def label_text(text):
    """Criteria label for one review. Returns LabelResult(label, rule, pos, neg, hits).
    label is None and rule is 'none' when no rule fires (caller falls back to the star)."""
    hits, norm = _scan(text)
    serious = [h for h in hits if h.pol == "neg" and h.strength == "S"]
    pos = sum(h.strength for h in hits if h.pol == "pos")
    neg = sum(h.strength for h in hits if h.pol == "neg" and h.strength != "S")
    has_neu = any(h.id == "N-neutral-phrase" for h in hits)
    has_fact = any(h.id == "F-factual-receipt" for h in hits)
    has_praise = any(h.pol == "pos" and h.strength >= 2 for h in hits)

    def R(label, rule):
        return LabelResult(label, rule, pos, neg, hits)

    if serious:                                                         # R1
        return R(NEG, "R1_verdict_negative" if any(h.id.startswith("V-neg") for h in serious)
                 else "R1_serious_unresolved")
    sarcastic = ((SARCASM_CUE.search(norm) and any(h.pol == "neg" and h.strength == 2 for h in hits))
                 or (ABSENCE.search(norm) and has_praise))
    if sarcastic:                                                       # R2
        return R(NEG, "R2_sarcasm")
    if pos == 0 and neg == 0:                                           # R3 / R5
        if has_neu:  return R(NEU, "R5_neutral_expression")
        if has_fact: return R(NEU, "R5_factual_no_evaluation")
        return R(None, "none")
    if neg == 0:                                                        # positive only
        if (has_neu or has_fact) and pos <= 1:
            return R(NEU, "R5_neutral_expression")
        return R(POS, "R3_positive")
    if pos == 0:                                                        # negative only
        if neg >= 2:
            return R(NEG, "R3_negative")
        if has_neu:
            return R(NEU, "R5_neutral_expression")
        return R(None, "none")                  # one minor complaint alone is not enough to decide
    margin = pos - neg                                                  # R4: mixed review
    if margin >= 2:  return R(POS, "R4_mixed_positive_dominates")
    if margin <= -2: return R(NEG, "R4_mixed_negative_dominates")
    return R(NEU, "R4_mixed_balanced")

def criteria_label(text):
    r = label_text(text)
    return r.label, r.rule

